"""Generate SYNTHETIC occupancy history for the Premium forecast.

    python scripts/generate_history.py            # writes data/occupancy_history.csv
    python scripts/generate_history.py --backtest  # also prints forecast accuracy on the last week

Nothing here is real data. Every 15 minutes while the library is open, for 5 weeks, it writes an
occupancy score on the same 0-1 scale as the live status (0 = not full, 0.8 = ~80%, 1 = full).

Assumptions (state these when presenting):
- Opening hours: Mon-Fri 08:00-22:00, Sat-Sun 10:00-18:00 (assumed, Europe/Dublin time).
- Daily shape: quiet at opening, peak around 14:00-15:00, easing in the evening. Shape it to
  public evidence where possible (e.g. Google Maps "Popular times" for the James Joyce Library).
- Mon-Wed busiest, Friday lighter, weekends quiet.
- Each week is busier than the last as exams approach.
- Some days are busier or quieter than usual overall, and conditions drift within a day.
"""
import argparse
import csv
import random
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from library import forecast  # noqa: E402

END_DATE = date(2026, 10, 9)  # last day of history (fixed so the committed CSV is reproducible)
WEEKS = 5
SEED = 2026

# Typical weekday occupancy by hour (linearly interpolated between hours).
HOURLY = {8: .10, 9: .25, 10: .45, 11: .62, 12: .72, 13: .80, 14: .86, 15: .85, 16: .78,
          17: .65, 18: .52, 19: .42, 20: .32, 21: .20, 22: .10}
WEEKDAY_FACTOR = [1.00, 1.05, 1.03, 0.95, 0.78, 0.55, 0.60]  # Mon..Sun


def base_curve(hour_float):
    lower = max(h for h in HOURLY if h <= hour_float)
    upper = min((h for h in HOURLY if h > hour_float), default=lower)
    if upper == lower:
        return HOURLY[lower]
    t = hour_float - lower
    return HOURLY[lower] * (1 - t) + HOURLY[upper] * t


def generate(end_date=END_DATE, weeks=WEEKS, seed=SEED):
    rng = random.Random(seed)
    start = end_date - timedelta(days=weeks * 7 - 1)
    rows = []
    for day_index in range(weeks * 7):
        day = start + timedelta(days=day_index)
        exam_factor = 0.88 + 0.06 * (day_index // 7)   # each week busier than the last
        day_offset = rng.gauss(0, 0.07)                   # busier/quieter day overall
        drift = 0.0                                       # conditions that persist for a while
        opens, closes = forecast.OPEN_HOURS[day.weekday()]
        slot_time = datetime(day.year, day.month, day.day, opens)
        while slot_time.hour < closes:
            drift = 0.85 * drift + rng.gauss(0, 0.03)
            hour = slot_time.hour + slot_time.minute / 60
            score = base_curve(hour) * WEEKDAY_FACTOR[day.weekday()] * exam_factor + day_offset + drift
            rows.append((slot_time, round(min(1.0, max(0.0, score)), 3)))
            slot_time += timedelta(minutes=forecast.SLOT_MINUTES)
    return rows


def write_csv(rows, path=forecast.HISTORY_PATH):
    path.parent.mkdir(exist_ok=True)
    with open(path, 'w', newline='') as f:
        f.write('# SYNTHETIC data generated by scripts/generate_history.py. Not real library occupancy.\n')
        writer = csv.writer(f)
        writer.writerow(['local_time', 'score'])
        for slot_time, score in rows:
            writer.writerow([slot_time.isoformat(timespec='minutes'), score])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--backtest', action='store_true', help='print accuracy on the final week')
    args = parser.parse_args()
    rows = generate()
    write_csv(rows)
    print(f'Wrote {len(rows)} synthetic rows to {forecast.HISTORY_PATH.relative_to(ROOT)}')
    if args.backtest:
        for noise, title in ((0.0, 'perfect live readings'), (0.15, 'noisy live readings (sd 0.15, like real reports)')):
            result = forecast.backtest(rows, live_noise=noise)
            print(f"\nBacktest with {title}: trained on {result['train_days']} days, tested on the last "
                  f"{result['test_days']} days ({result['test_points']} one-hour-ahead predictions)")
            print('Mean absolute error (lower is better, scale 0-1):')
            for name, mae in result['mae'].items():
                print(f'  {name:32s} {mae:.3f}')
            print(f"Level correct with LIVE_WEIGHT={forecast.LIVE_WEIGHT}: {result['level_accuracy']:.0%} "
                  f"(\"same as now\" baseline: {result['baseline_level_accuracy']:.0%})")


if __name__ == '__main__':
    main()
